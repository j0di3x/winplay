#!/usr/bin/env python3
"""Writes Resources/<lang>.lproj/Localizable.strings from Tools/l10n/<lang>.json and checks them.
Each JSON maps the English text (the key used in Sources/main.swift) to its translation.
Run: python3 Tools/l10n/build.py      (fails when a key is missing or a %@ / %ld does not match)"""
import json, re, sys, pathlib
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
from keys import keys

def specs(s):
    return sorted(re.findall(r"%(?:@|ld|d|lld)", s))

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

problems = 0
langs = sorted(p.stem for p in HERE.glob("*.json"))
for lang in ["en"] + langs:
    table = {k: k for k in keys} if lang == "en" else json.loads((HERE / f"{lang}.json").read_text())
    out = [f"/* WinPlay, {lang}. Generated by Tools/l10n/build.py from Tools/l10n/{lang}.json; edit that file. */", ""]
    for k in keys:
        v = table.get(k)
        if v is None:
            print(f"{lang}: missing: {k}"); problems += 1; v = k
        elif specs(v) != specs(k):
            print(f"{lang}: format mismatch: {k!r} -> {v!r}"); problems += 1
        out.append(f'"{esc(k)}" = "{esc(v)}";')
    for k in table:
        if k not in keys:
            print(f"{lang}: unused (remove it): {k}")
    d = ROOT / "Resources" / f"{lang}.lproj"
    d.mkdir(parents=True, exist_ok=True)
    (d / "Localizable.strings").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(keys)} strings, languages: en {' '.join(langs)}")
sys.exit(1 if problems else 0)
